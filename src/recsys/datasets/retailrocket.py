"""RetailRocket e-commerce dataset adapter.

Source: "Retailrocket recommender system dataset" (Kaggle: retailrocket/ecommerce-dataset),
license CC BY-NC-SA 4.0: non-commercial use, attribution, share-alike. Raw and
prepared data are never committed (they live under gitignored data/).

What's in it: ~4.5 months (May–Sep 2015) of a real online store's events
(view, addtocart, transaction) for ~1.4M visitors and ~235k items, plus item
property snapshots over time (category, availability; other properties are
hashed) and a category tree.

`prepare` converts it to the engine's standard layout:

    OUT/catalog/catalog.yaml + items.csv   generic catalog (category path as tags)
    OUT/interactions.csv                   view / add_to_cart / purchase, sessionized
    OUT/availability.csv                   when each item went in or out of stock
    OUT/README.md                          provenance + license
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from recsys.sessions import DEFAULT_GAP

NAME = "retailrocket"
LICENSE = "CC BY-NC-SA 4.0 (non-commercial, attribution, share-alike)"
SOURCE = "https://www.kaggle.com/datasets/retailrocket/ecommerce-dataset"
# A public mirror of the same files (no account needed). Check the license above before use.
MIRROR = (
    "https://huggingface.co/datasets/DanielKiani/RetailRocket-Recommender-Data/resolve/main/"
    "data/RetailRocket-Recommender-Data/data"
)
FILES = (
    "events.csv",
    "category_tree.csv",
    "item_properties_part1.csv",
    "item_properties_part2.csv",
)
KINDS = {"view": "view", "addtocart": "add_to_cart", "transaction": "purchase"}

CATALOG_YAML = """\
# Generated by `recsys dataset prepare retailrocket`. Item names and most
# properties are hashed in the source, so items are described by category only.
item_id: item_id
title: title
description: null
category: category
image_url: null
tag_facets:
  # Leaf category plus every ancestor, so items in sibling categories still overlap.
  category: {column: category_path, multi: true}
  # Top-level category: the unit for "did the shopper move into a new category?"
  department: {column: department}
  # Second level (136 of them): the "product type" for shopper profiles.
  type: {column: type}
"""


def _pandas() -> Any:
    try:
        import pandas as pd
    except ImportError as exc:  # pragma: no cover - environment guidance
        raise RuntimeError("dataset tools need pandas: uv sync --extra datasets") from exc
    return pd


def download(raw_dir: Path) -> list[Path]:
    """Fetch the raw files from the public mirror (≈1 GB). Skips files already present."""
    import shutil
    import urllib.request

    raw_dir.mkdir(parents=True, exist_ok=True)
    fetched = []
    for name in FILES:
        target = raw_dir / name
        if not target.exists():
            tmp = target.with_suffix(".part")
            with urllib.request.urlopen(f"{MIRROR}/{name}") as response, tmp.open("wb") as f:
                shutil.copyfileobj(response, f)
            tmp.rename(target)
        fetched.append(target)
    return fetched


def _category_paths(tree: Any) -> dict[int, list[int]]:
    """categoryid -> [root, ..., categoryid] (cycle-safe)."""
    parent = {
        int(c): (int(p) if p == p else None)  # NaN check: NaN != NaN
        for c, p in zip(tree.categoryid, tree.parentid, strict=True)
    }
    paths: dict[int, list[int]] = {}
    for cat in parent:
        path, node, seen = [], cat, set()
        while node is not None and node not in seen:
            seen.add(node)
            path.append(node)
            node = parent.get(node)
        paths[cat] = path[::-1]
    return paths


def _properties(raw_dir: Path, keep: set[str]) -> Any:
    """Read only the properties we use, in chunks (the files total ~20M rows)."""
    pd = _pandas()
    parts = []
    for name in ("item_properties_part1.csv", "item_properties_part2.csv"):
        path = raw_dir / name
        if not path.exists():
            continue
        for chunk in pd.read_csv(path, chunksize=2_000_000, dtype={"value": str}):
            parts.append(chunk[chunk.property.isin(keep)])
    if not parts:
        return pd.DataFrame(columns=["timestamp", "itemid", "property", "value"])
    return pd.concat(parts, ignore_index=True)


def prepare(raw_dir: Path, out_dir: Path, *, gap_minutes: float | None = None) -> dict[str, int]:
    pd = _pandas()
    raw_dir, out_dir = Path(raw_dir), Path(out_dir)
    gap_ms = (gap_minutes * 60_000) if gap_minutes else DEFAULT_GAP.total_seconds() * 1000

    # -- interactions, sessionized exactly like recsys.sessions.sessionize -------
    ev = pd.read_csv(raw_dir / "events.csv", usecols=["timestamp", "visitorid", "event", "itemid"])
    ev = ev[ev.event.isin(KINDS)].sort_values(["visitorid", "timestamp"], kind="stable")
    new_visitor = ev.visitorid.ne(ev.visitorid.shift())
    new_session = new_visitor | ev.timestamp.diff().gt(gap_ms)
    session_n = new_session.astype(int).groupby(ev.visitorid).cumsum() - 1
    interactions = pd.DataFrame(
        {
            "user_id": ev.visitorid.astype(str),
            "item_id": ev.itemid.astype(str),
            "kind": ev.event.map(KINDS),
            "value": 1,
            "occurred_at": pd.to_datetime(ev.timestamp, unit="ms", utc=True).map(
                lambda t: t.isoformat()
            ),
            "session_id": ev.visitorid.astype(str) + ":" + session_n.astype(str),
        }
    )

    # -- catalog: items seen in events, described by their category path ---------
    props = _properties(raw_dir, {"categoryid", "available"})
    props = props[props.itemid.isin(set(ev.itemid))].sort_values(["itemid", "timestamp"])
    paths = _category_paths(pd.read_csv(raw_dir / "category_tree.csv"))
    cats = props[props.property == "categoryid"].groupby("itemid").value.last()
    items = pd.DataFrame({"item_id": sorted(set(ev.itemid))})
    leaf = items.item_id.map(cats).astype("Int64")
    items["title"] = "Item " + items.item_id.astype(str)
    items["category"] = leaf.astype(str).where(leaf.notna(), "")
    items["category_path"] = leaf.map(
        lambda c: ";".join(map(str, paths.get(int(c), [int(c)]))) if c is not pd.NA else ""
    )
    items["department"] = items.category_path.str.split(";").str[0]
    levels = items.category_path.str.split(";")
    items["type"] = levels.str[1].where(levels.str.len() > 1, items.department)
    items["item_id"] = items.item_id.astype(str)

    # -- availability changes over time (keep only actual flips) ------------------
    avail = props[props.property == "available"][["itemid", "timestamp", "value"]].copy()
    avail["available"] = avail.value.astype(str).str.strip().eq("1")
    changed = avail.available.ne(avail.groupby("itemid").available.shift())
    avail = avail[changed]
    availability = pd.DataFrame(
        {
            "item_id": avail.itemid.astype(str),
            "valid_from": pd.to_datetime(avail.timestamp, unit="ms", utc=True).map(
                lambda t: t.isoformat()
            ),
            "available": avail.available.map({True: "true", False: "false"}),
        }
    )

    (out_dir / "catalog").mkdir(parents=True, exist_ok=True)
    (out_dir / "catalog" / "catalog.yaml").write_text(CATALOG_YAML)
    items.to_csv(out_dir / "catalog" / "items.csv", index=False)
    interactions.to_csv(out_dir / "interactions.csv", index=False)
    availability.to_csv(out_dir / "availability.csv", index=False)
    (out_dir / "README.md").write_text(
        f"# RetailRocket (prepared)\n\nSource: {SOURCE}\nLicense: {LICENSE}\n\n"
        "Generated by `recsys dataset prepare retailrocket`. Do not commit or redistribute.\n"
    )
    return {
        "items": len(items),
        "items_with_category": int(leaf.notna().sum()),
        "interactions": len(interactions),
        "sessions": int(new_session.sum()),
        "users": int(new_visitor.sum()),
        "availability_changes": len(availability),
    }
