"""OTTO e-commerce dataset adapter.

Source: "OTTO – Recommender Systems Dataset" (github.com/otto-de/recsys-dataset;
files on Kaggle: otto/recsys-dataset), license CC BY 4.0: commercial use
allowed with attribution. Raw and prepared data are never committed (they
live under gitignored data/).

What's in it: 4 weeks (Aug 2022) of clicks, carts and orders from OTTO, a
large German online retailer: ~12.9M shoppers, ~1.8M articles, ~216M events.
An OTTO "session" is one anonymous shopper's whole period, so it is our user.
Articles are anonymized ids: no title, category, price or brand.

`prepare` converts it to the engine's standard layout, keeping shoppers whose
id is a multiple of `sample_every` (default 64, ≈200k shoppers and ≈3.4M
events, about RetailRocket's size) so their histories stay complete:

    OUT/catalog/catalog.yaml + items.csv   articles seen in the sample (ids only)
    OUT/interactions.csv                   view / add_to_cart / purchase, sessionized
    OUT/README.md                          provenance + license
"""

from __future__ import annotations

import json
import zipfile
from pathlib import Path
from typing import Any

from recsys.sessions import DEFAULT_GAP

NAME = "otto"
LICENSE = "CC BY 4.0 (attribution; commercial use allowed)"
SOURCE = "https://github.com/otto-de/recsys-dataset"
# A public mirror of the official Kaggle zip (no account needed), ≈2 GB.
MIRROR = "https://huggingface.co/datasets/hazemessam/otto-recsys/resolve/main/train.jsonl"
RAW_FILE = "train.zip"
KINDS = {"clicks": "view", "carts": "add_to_cart", "orders": "purchase"}

CATALOG_YAML = """\
# Generated by `recsys dataset prepare otto`. Articles are anonymized ids with
# no category, price or brand, so category- and price-based sources stay idle.
item_id: item_id
title: title
description: null
category: null
image_url: null
"""


def _pandas() -> Any:
    try:
        import pandas as pd
    except ImportError as exc:  # pragma: no cover - environment guidance
        raise RuntimeError("dataset tools need pandas: uv sync --extra datasets") from exc
    return pd


def download(raw_dir: Path) -> list[Path]:
    """Fetch the training file from the public mirror (≈2 GB zip). Skips it if present."""
    import shutil
    import urllib.request

    raw_dir.mkdir(parents=True, exist_ok=True)
    target = raw_dir / RAW_FILE
    if not target.exists():
        tmp = target.with_suffix(".part")
        with urllib.request.urlopen(MIRROR) as response, tmp.open("wb") as f:
            shutil.copyfileobj(response, f)
        tmp.rename(target)
    return [target]


def _lines(raw_dir: Path):  # type: ignore[no-untyped-def]
    """JSON lines from train.zip (the official archive) or a plain train.jsonl."""
    path = raw_dir / RAW_FILE
    if path.exists() and zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z, z.open(z.namelist()[0]) as f:
            yield from f
    else:
        with (raw_dir / "train.jsonl").open("rb") as f:
            yield from f


def prepare(
    raw_dir: Path,
    out_dir: Path,
    *,
    gap_minutes: float | None = None,
    sample_every: int = 64,
) -> dict[str, int]:
    pd = _pandas()
    raw_dir, out_dir = Path(raw_dir), Path(out_dir)
    gap_ms = (gap_minutes * 60_000) if gap_minutes else DEFAULT_GAP.total_seconds() * 1000

    users, items, kinds, ts = [], [], [], []
    shoppers = 0
    for line in _lines(raw_dir):
        # The session id leads each line ({"session":123,...}): skip without parsing.
        sid = int(line[11 : line.index(b",")])
        if sid % sample_every:
            continue
        shoppers += 1
        for e in json.loads(line)["events"]:
            users.append(sid)
            items.append(e["aid"])
            kinds.append(e["type"])
            ts.append(e["ts"])
    ev = pd.DataFrame({"user": users, "item": items, "kind": kinds, "ts": ts})
    del users, items, kinds, ts
    ev = ev.sort_values(["user", "ts"], kind="stable")

    # -- sessionized exactly like recsys.sessions.sessionize ---------------------
    new_user = ev.user.ne(ev.user.shift())
    new_session = new_user | ev.ts.diff().gt(gap_ms)
    session_n = new_session.astype(int).groupby(ev.user).cumsum() - 1
    when = pd.to_datetime(ev.ts, unit="ms", utc=True)
    interactions = pd.DataFrame(
        {
            "user_id": ev.user.astype(str),
            "item_id": ev.item.astype(str),
            "kind": ev.kind.map(KINDS),
            "value": 1,
            "occurred_at": when.dt.strftime("%Y-%m-%dT%H:%M:%S.%f+00:00"),
            "session_id": ev.user.astype(str) + ":" + session_n.astype(str),
        }
    )
    catalog = pd.DataFrame({"item_id": sorted(set(ev.item))})
    catalog["title"] = "Article " + catalog.item_id.astype(str)

    (out_dir / "catalog").mkdir(parents=True, exist_ok=True)
    (out_dir / "catalog" / "catalog.yaml").write_text(CATALOG_YAML)
    catalog.to_csv(out_dir / "catalog" / "items.csv", index=False)
    interactions.to_csv(out_dir / "interactions.csv", index=False)
    (out_dir / "README.md").write_text(
        f"# OTTO (prepared, 1 in {sample_every} shoppers)\n\nSource: {SOURCE}\n"
        f"License: {LICENSE}\n\nGenerated by `recsys dataset prepare otto`. "
        "Do not commit; cite OTTO if you redistribute.\n"
    )
    return {
        "items": len(catalog),
        "interactions": len(interactions),
        "sessions": int(new_session.sum()),
        "users": shoppers,
    }
